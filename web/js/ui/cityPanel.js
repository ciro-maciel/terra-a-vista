import { css } from "../color.js";
import { esc } from "../format.js";
import { isCapital } from "../world.js";
import { yieldGrid, amenities, industries, gdpRow, popLine, growthSpan, showPanel, hidePanel } from "./infoPanel.js";
import { tr } from "../i18n.js";

/**
 * ctx: {w, nation, onClose, onPedia, onState(stateIndex)}
 */
export function openCityPanel(city, ctx) {
  const { w, nation } = ctx;
  const n = nation.nation;
  const owner = city.cell != null ? w.raw.owner[city.cell] : -1;
  const col = css(w.stateColor[owner] || [190, 190, 190]);

  // The city's states as links to their state panels.
  const states = (city.states || [])
    .map((abbr) => ({ abbr, i: w.raw.states.findIndex((s) => s.abbr === abbr) }))
    .map(({ abbr, i }) => (i >= 0 && ctx.onState
      ? `<button class="chip" data-state="${i}" title="${tr("Abrir {0}", esc(w.raw.states[i].name))}">${esc(abbr)}</button>`
      : `<span class="chip">${esc(abbr)}</span>`))
    .join("");

  const growth = growthSpan(city, n);

  showPanel({
    kind: "city",
    stripe: col,
    title: city.name,
    titleHtml: `${isCapital(city) ? `<span class="cap" title="${tr("Capital federal")}">★</span> ` : ""}${esc(city.name)}`,
    sub: `${esc(city.full || "")}${states ? `<div class="chips">${states}</div>` : ""}`,
    headExtra: popLine(city, growth),
    sections: [
      { title: tr("Rendimentos"), html: `<div class="yield-grid">${yieldGrid(nation, city.yields)}</div>` },
      { title: tr("Qualidade de vida e moradia"), html: amenities(city, n) + gdpRow(city) },
      { title: tr("Atividades · onde as pessoas trabalham"), html: industries(city, nation) },
    ],
    foot: tr("Fonte: IBGE, {0}; empregos: IBGE, Cadastro Central de Empresas{1}.\n      ×N em verde = a parcela dos empregos desta atividade é N vezes a parcela no Brasil.", esc(nation.vintage), nation.gdp_vintage ? `; PIB: ${esc(nation.gdp_vintage)}` : ""),
    onClose: ctx.onClose,
    onPedia: ctx.onPedia,
    wire(panel) {
      panel.querySelectorAll("[data-state]").forEach((b) => (b.onclick = () => ctx.onState(+b.dataset.state)));
    },
  });
}

export const closeCityPanel = hidePanel;
